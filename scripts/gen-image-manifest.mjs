#!/usr/bin/env node
/**
 * @file gen-image-manifest.mjs
 * @description Derive the REAL image inventory from disk (never hand-pinned).
 *
 * The stills/diary carousels load images by contiguous index (media1..mediaN),
 * but the archive is SPARSE and uses suffixes (media gaps: 1,3,4,7,8,12-23,32,33,40-44;
 * diary has 'a' variants: diary10, diary10a). Index-built paths therefore 404.
 *
 * This scans img/photos/<collection> and emits js/imageManifest.js — an explicit
 * list of the identifiers that actually exist, so the gallery can load only real
 * files (and produce correct totals) instead of guessing a range. Re-run after
 * adding photos: `node scripts/gen-image-manifest.mjs`.
 */
import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PHOTOS = join(ROOT, 'img', 'photos');

// Carousel-backed collections: stem === folder name, files are `${stem}<id>.jpg`.
const COLLECTIONS = ['media', 'faster', 'slip', 'live', 'diary'].map((name) => ({ name }));
// Archive folders not yet wired to a chamber — inventoried for future fortification.
const ARCHIVE = [
  // Folder is glitchpr0n, but files are named glitch1.png, glitch2.png, ...
  { name: 'glitchpr0n', stem: 'glitch' },
  { name: 'random' },
];

/** Natural sort so '2' < '10' < '10a'. */
const naturalSort = new Intl.Collator(undefined, { numeric: true, sensitivity: 'base' }).compare;

function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function identifiersFor({ name, stem = name }) {
  const dir = join(PHOTOS, name);
  if (!existsSync(dir)) return [];
  const re = new RegExp(`^${escapeRegExp(stem)}([\\w-]+)\\.(jpe?g|png|gif)$`, 'i');
  return readdirSync(dir)
    .map((f) => (re.exec(f) || [])[1])
    .filter(Boolean)
    .sort(naturalSort);
}

const manifest = {};
for (const c of [...COLLECTIONS, ...ARCHIVE]) manifest[c.name] = identifiersFor(c);

const banner =
  '// AUTO-GENERATED by scripts/gen-image-manifest.mjs — do not edit by hand.\n' +
  '// Identifiers that actually exist on disk, per collection (sparse + suffixed).\n';
const body =
  banner +
  "'use strict';\n" +
  'const IMAGE_MANIFEST = ' +
  JSON.stringify(manifest, null, 2) +
  ';\n' +
  "if (typeof module !== 'undefined') module.exports = { IMAGE_MANIFEST };\n";

writeFileSync(join(ROOT, 'js', 'imageManifest.js'), body);

const counts = Object.entries(manifest)
  .map(([k, v]) => `${k}=${v.length}`)
  .join('  ');
console.log('wrote js/imageManifest.js  ' + counts);
